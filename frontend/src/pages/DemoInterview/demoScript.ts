export const SECONDARY_HINT = "也可以稍后上传简历，让 AI 从你的经历开始了解你。";

/* ------------------------------------------------------------------ *
 * 逐轮追问
 * ------------------------------------------------------------------ */

/**
 * 根据"已完成轮次 + 历史输入"生成下一句 AI 追问。
 *
 * @param turn 已经发生的用户发言条数（第 1 次发送后 turn = 1）
 * @param last 用户最近一条发言
 */
export function nextQuestion(turn: number, last: string): string {
  const subject = pickSubject(last);
  const span = quoteSpan(last);
  const ref = subject ? `「${subject}」` : span ? `你说的「${span}」` : "刚才那段";

  switch (turn) {
    // 第 2 轮：追问具体任务（识别项目/公司/任务/角色）
    case 1:
      return subject
        ? `「${subject}」这段听起来有内容。你在里面具体负责的是哪一部分？`
        : "听起来你有一些具体经历。挑其中最有代表性的一段——你当时具体做了什么？";

    // 第 3 轮：追问行动与结果
    case 2:
      return HAS_NUMBER.test(last)
        ? `${ref}你提到了结果，这个能再具体一点吗？比如一个能被衡量的变化。`
        : `${ref}后来带来了什么变化？有没有一个能被衡量的结果，哪怕是体验上的改善？`;

    // 第 4 轮：追问成就感 / 消耗感
    case 3:
      return `那这段经历里，哪一部分让你最有成就感？又有没有哪一部分，是让你觉得特别消耗的？`;

    // 第 5 轮：追问工作方式偏好（独立 vs 协作）
    case 4:
      if (HAS_SOLO.test(last) && !HAS_TEAM.test(last)) {
        return "听起来你更习惯自己把事情推下去。那如果换成需要反复和别人对齐的场景，你会觉得别扭，还是也能接受？";
      }
      if (HAS_TEAM.test(last) && !HAS_SOLO.test(last)) {
        return "你提到协作比较多。那有没有那种「只能你一个人拍板、没人帮你」的时刻？你在那种状态下是舒服还是难受？";
      }
      return "把刚才这些经历放在一起看，你更喜欢自己独立推进，还是和别人一起协作完成？为什么？";

    // 第 6 轮：追问价值取向 / 工作环境
    case 5:
      return "如果只能选一个，你更在意成长速度、稳定性、自主空间，还是最终能看到自己的成果？选完说说为什么。";

    // 第 7 轮：追问反例 / 边界
    case 6:
      return HAS_AVOID.test(last)
        ? "这个我记下了。除了刚才那条，还有没有别的、你觉得以后明确不想再接受的？"
        : "反过来问一句：有没有一种工作方式，是你以后明确不想接受的？";

    // 第 8 轮：总结确认（不直接生成画像，先让用户校对理解）
    case 7:
      return buildReflection(last);

    default:
      return "";
  }
}

/** 生成"阶段性理解 + 不确定项"的收束问句（第 8 轮）。 */
function buildReflection(last: string): string {
  const solo = HAS_SOLO.test(last);
  const team = HAS_TEAM.test(last);
  const lean = solo && !team ? "能自己把事情推下去" : team && !solo ? "在协作里把事情做成" : "既有自己的判断、也能配合别人";

  return [
    "我大概理了一下，说给你听听——",
    `你可能更偏向「${lean}」，在意的是做出来的东西真的起作用，而不只是把任务交掉；`,
    "在选择上，你愿意为了成长和自主空间让掉一部分确定性。",
    "",
    "不过有两点我还不确定：一是压力大的时候，你更需要人给方向，还是更需要空间自己扛；",
    "二是你对「稳定」的容忍度到底有多低。",
    "",
    "这些理解和你自己的感觉一致吗？有哪里我想偏了？",
  ].join("\n");
}

