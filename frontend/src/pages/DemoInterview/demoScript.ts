/**
 * 在线 Demo 的「AI 认识你」冷启动访谈脚本。
 *
 * 为什么放在前端而不是调后端 interview_step：
 *  - Demo 账号是**多人共用**的，而 career_interview_session.user_id 是 UNIQUE。
 *    走后端会让访客 A 的答题状态影响访客 B（甚至把先来的会话推到 completed，
 *    后来的直接撞「访谈已完成」报错），且 append_turn 会持续污染同一份会话。
 *  - 本模块是**纯确定性函数**：不联网、不调用任何 LLM、零费用、可单测。
 *
 * 追问不是静态问卷：每一轮都会从**用户真实输入**里抽取可引用的片段
 * （公司 / 项目 / 数字 / 偏好 / 反例），再据此组织下一问，
 * 形成"用户说了一件事 → AI 识别主体 → 继续追问 → 根据前文改变问题"的连贯访谈。
 *
 * ⚠️ 本文件里的所有经历、公司名、数字均为**虚构示例**，与任何真实用户无关。
 */

/** 访谈总轮次（7-8 轮有效问答）。 */
export const TOTAL_TURNS = 8;

/** 首屏主 CTA 的引导语（对应 §一 的单一入口）。 */
export const INTRO_OPENER =
  "好，我们随便聊聊。先讲一段你做过、也比较有印象的经历吧——在哪里、大概做什么，" +
  "你印象最深的是哪一部分？";

/* ------------------------------------------------------------------ *
 * 主体抽取
 * ------------------------------------------------------------------ */

/** 从自由文本里抽取一个可引用的"主体"（公司 / 项目 / 引号内容）。 */
export function pickSubject(text: string): string | null {
  const t = (text || "").trim();
  if (!t) return null;

  // 「XX」/ “XX” / "XX" —— 用户自己强调过的名词最值得引用
  const quoted = t.match(/[「“"]([^」”"]{2,16})[」”"]/);
  if (quoted) return quoted[1] ?? null;

  // 「在 XX 公司/团队/项目…」
  const org = t.match(
    /在([\u4e00-\u9fa5A-Za-z0-9]{2,12}?)(?:公司|集团|科技|工作室|团队|部门|项目|实习)/
  );
  if (org) return org[1] ?? null;

  // 「XX 公司/项目」出现在句首
  const head = t.match(/^([\u4e00-\u9fa5A-Za-z0-9]{2,12}?)(?:公司|集团|工作室|项目)/);
  if (head) return head[1] ?? null;

  // 「做过 / 负责一个 XX」——要求 XX 不是「一些/一堆/点/些」这类量词开头，
  // 否则会把"做过一些杂事"误当成主体名引出来（宁可落回通用问句）。
  const act = t.match(
    /(?:做过|做了一个|参与了一个|负责了?一个)(?!一些|一堆|一点|些|点)([\u4e00-\u9fa5A-Za-z0-9]{2,10}?)(?:的|，|,|。|$)/
  );
  if (act) return act[1] ?? null;

  // 「做过 XX」：XX 必须是具体名词，排除"一些/很多/不少"等泛量词
  const did = t.match(/(?:做过|负责过|参与过)(?!一些|很多|不少|不少|些)([\u4e00-\u9fa5]{3,10})(?:，|,|。|$)/);
  if (did) {
    const cand = did[1] ?? null;
    if (cand && !/^(一些|很多|不少|各种|很多事|这些|那些)/.test(cand)) return cand;
  }

  return null;
}

/* ------------------------------------------------------------------ *
 * 语义探测（决定追问往哪个方向走）
 * ------------------------------------------------------------------ */

const HAS_NUMBER = /\d|百分|提升|增长|降低|下降|收益|指标|转化|留存|成|倍/;
const HAS_ACTION = /负责|主导|推进|落地|协调|搭建|设计|分析|执行|策划|运营|跟进|优化/;
const HAS_EMOTION = /成就|有意义|开心|满足|喜欢|享受|消耗|累|疲惫|烦|没意思|难受|委屈|煎熬|内耗/;
const HAS_SOLO = /独立|自己|一个人|单独|自主/;
const HAS_TEAM = /团队|协作|一起|配合|伙伴|同事|沟通/;
const HAS_AVOID = /不想|不愿意|不接受|避免|讨厌|排斥|不能接受|拒绝|受不了/;

/** 从文本里取一个"金句"片段：优先含情绪/行动词的分句，否则取首句。 */
function quoteSpan(text: string): string {
  const t = (text || "").replace(/\s+/g, " ").trim();
  if (!t) return "";
  const clauses = t.split(/[。；;！!？?]/).map((s) => s.trim()).filter(Boolean);
  const hit = clauses.find((c) => HAS_EMOTION.test(c)) ?? clauses.find((c) => HAS_ACTION.test(c)) ?? clauses[0] ?? "";
  return hit.length > 34 ? `${hit.slice(0, 34)}…` : hit;
}

